impl Strings {
    pub fn pick<'a>(&self, en: &'a str, tr: &'a str, ru: &'a str) -> &'a str {
        match self.lang {
            Language::English => en,
            Language::Turkish => tr,
            Language::Russian => ru,
        }
    }

    pub fn format_sell_confirm(&self, count: usize, total: &str) -> String {
        self.sell_confirm_pattern
            .replace("{count}", &count.to_string())
            .replace("{total}", total)
    }
}

